#!/usr/bin/env python3
"""
Video to Web-Optimized Media Converter for Flutter GetX MVC Boilerplate.
Converts raw screen recordings (.mp4/.mov) into lightweight Animated WebP and FastStart MP4.
Generates an automatic horizontal showcase table in Markdown.
"""

import os
import re
import subprocess
import sys
from pathlib import Path

# Paths
BASE_DIR = Path(__file__).resolve().parent.parent
RAW_DIR = BASE_DIR / "recordings" / "raw"
OPT_DIR = BASE_DIR / "recordings" / "optimized"
SHOWCASE_MD = BASE_DIR / "recordings" / "SHOWCASE.md"

VIDEO_EXTENSIONS = {".mp4", ".mov", ".mkv", ".avi", ".webm"}


def natural_sort_key(s):
    """Sort strings with numbers naturally (e.g. scene1, scene2, scene10)."""
    return [int(text) if text.isdigit() else text.lower() for text in re.split(r'(\d+)', str(s))]


def format_bytes(size):
    """Format bytes into human-readable string."""
    for unit in ['B', 'KB', 'MB', 'GB']:
        if size < 1024.0:
            return f"{size:.1f} {unit}"
        size /= 1024.0
    return f"{size:.1f} TB"


def run_command(cmd):
    """Run shell command and return stdout/stderr."""
    result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"Command failed:\n{' '.join(cmd)}\nError:\n{result.stderr}")
    return result.stdout


def optimize_video(input_path: Path):
    """Convert a single video file to web-optimized WebP and MP4."""
    stem = input_path.stem
    output_webp = OPT_DIR / f"{stem}.webp"
    output_mp4 = OPT_DIR / f"{stem}_web.mp4"

    orig_size = input_path.stat().st_size
    print(f"\n🎬 Processing: {input_path.name} ({format_bytes(orig_size)})")

    # 1. Convert to Animated WebP (320px width, 15 fps, q:55, -2 height for even dimensions)
    print("   ↳ 🔄 Generating Web-Optimized WebP...")
    cmd_webp = [
        "ffmpeg", "-y", "-i", str(input_path),
        "-vf", "fps=15,scale=320:-2:flags=lanczos",
        "-vcodec", "libwebp",
        "-lossless", "0",
        "-q:v", "55",
        "-compression_level", "6",
        "-loop", "0",
        "-an",
        str(output_webp)
    ]
    run_command(cmd_webp)
    webp_size = output_webp.stat().st_size
    webp_saved = (1.0 - (webp_size / orig_size)) * 100 if orig_size > 0 else 0
    print(f"   ↳ ✅ WebP saved: {output_webp.name} ({format_bytes(webp_size)}) [{'-' if webp_saved >= 0 else '+'}{abs(webp_saved):.1f}%]")

    # 2. Convert to FastStart H.264 MP4 (360px width, crf 26, -2 height for even dimensions)
    print("   ↳ 🔄 Generating Web-Optimized MP4 (FastStart)...")
    cmd_mp4 = [
        "ffmpeg", "-y", "-i", str(input_path),
        "-c:v", "libx264",
        "-preset", "slow",
        "-crf", "26",
        "-pix_fmt", "yuv420p",
        "-movflags", "+faststart",
        "-vf", "scale=360:-2:flags=lanczos",
        "-an",
        str(output_mp4)
    ]
    run_command(cmd_mp4)
    mp4_size = output_mp4.stat().st_size
    mp4_saved = (1.0 - (mp4_size / orig_size)) * 100 if orig_size > 0 else 0
    print(f"   ↳ ✅ MP4 saved:  {output_mp4.name} ({format_bytes(mp4_size)}) [-{mp4_saved:.1f}%]")

    return {
        "name": stem,
        "orig_size": orig_size,
        "webp_path": output_webp,
        "webp_size": webp_size,
        "mp4_path": output_mp4,
        "mp4_size": mp4_size,
    }


def generate_horizontal_showcase(results):
    """Generate Markdown file displaying all scenes horizontally."""
    if not results:
        return

    md_lines = [
        "# 📱 Mobile App Flow Showcase (Horizontal Layout)",
        "",
        "> Auto-generated by `scripts/optimize_videos.py`. These files are local and git-ignored.",
        "",
        "## 🎬 Horizontal App Flow Grid",
        "",
        '<div align="center">',
        ""
    ]

    # Chunk into rows of 2 for beautiful horizontal side-by-side presentation
    chunk_size = 2
    for i in range(0, len(results), chunk_size):
        chunk = results[i:i + chunk_size]
        md_lines.append("<table>")
        md_lines.append("  <tr>")
        for item in chunk:
            title = item['name'].replace('_', ' ').replace('-', ' ').title()
            md_lines.append('    <td align="center" valign="top" width="320">')
            md_lines.append(f'      <b>{title}</b><br><br>')
            md_lines.append(f'      <picture>')
            md_lines.append(f'        <source srcset="optimized/{item["name"]}.webp" type="image/webp">')
            md_lines.append(f'        <img src="optimized/{item["name"]}.webp" width="280" alt="{title}" />')
            md_lines.append(f'      </picture><br>')
            md_lines.append(f'      <sub>WebP: {format_bytes(item["webp_size"])} &bull; MP4: {format_bytes(item["mp4_size"])}</sub>')
            md_lines.append('    </td>')
        md_lines.append("  </tr>")
        md_lines.append("</table>")
        md_lines.append("")

    md_lines.extend([
        "</div>",
        "",
        "---",
        "",
        "## 📊 Compression Statistics",
        "",
        "| Scene | Original Size | WebP Animated | Web MP4 (FastStart) | MP4 Savings |",
        "| :--- | :---: | :---: | :---: | :---: |"
    ])

    for item in results:
        orig = format_bytes(item['orig_size'])
        webp = format_bytes(item['webp_size'])
        mp4 = format_bytes(item['mp4_size'])
        savings = (1.0 - (item['mp4_size'] / item['orig_size'])) * 100 if item['orig_size'] > 0 else 0
        md_lines.append(f"| **{item['name']}** | {orig} | {webp} | {mp4} | **-{savings:.1f}%** |")

    SHOWCASE_MD.write_text("\n".join(md_lines), encoding="utf-8")
    print(f"\n🎉 Horizontal Showcase generated at: {SHOWCASE_MD}")


def main():
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    OPT_DIR.mkdir(parents=True, exist_ok=True)

    video_files = [f for f in RAW_DIR.iterdir() if f.is_file() and f.suffix.lower() in VIDEO_EXTENSIONS]
    video_files.sort(key=natural_sort_key)

    if not video_files:
        print("⚠️ No video files found in 'recordings/raw/'.")
        print("👉 Please copy your recorded .mp4 files into:")
        print(f"   {RAW_DIR}")
        print("   Then run this script again!")
        return

    print(f"🚀 Found {len(video_files)} video(s) in 'recordings/raw/'. Starting optimization...")
    results = []
    for f in video_files:
        res = optimize_video(f)
        results.append(res)

    generate_horizontal_showcase(results)
    print("\n✨ All videos successfully converted and web-optimized!")


if __name__ == "__main__":
    main()
